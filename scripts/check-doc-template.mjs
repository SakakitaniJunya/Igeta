#!/usr/bin/env node
// 設計書がテンプレート (templates/docs/*.md) の必須構造を満たしているか検証する。
// 文書体系の正典は docs/README.md、構造規約は docs/guides/01-document-taxonomy.md。
//
// kind は frontmatter が優先。無ければ **テンプレの配置と同じ docs 上の位置**から決まる
// (templates/docs/design/basic/tables/__context__.md → docs/design/basic/tables/*.md)。
// 両方あって食い違う場合は違反 (置き場所と宣言のどちらかが間違っている)。
//
// 検証内容: ① frontmatter の kind がテンプレ登録済み ② テンプレの必須 H2 節が全部ある
// ③ 「関連」節に上流・下流が 1 件以上 (表・箇条書きのどちらでもよい) ④ ID 接頭辞の形式 (PREFIX-nnn)
// ⑤ depends_on が実在する doc id を指す ⑥ TL;DR (how-to は When to use) がある
//
// exit 0 = 適合 / 1 = 違反 / 2 = 検査不能 (テンプレ・docs が無い、テンプレ自体が壊れている)

import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { basename, dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const EXIT_OK = 0;
const EXIT_VIOLATION = 1;
const EXIT_CANNOT_CHECK = 2;

const REPO_ROOT = resolve(fileURLToPath(import.meta.url), '..', '..');
const OPTIONAL_SUFFIX = '(任意)';
const SKIP_DIR = new Set(['node_modules', 'dist', 'coverage']);

function usage() {
  return [
    'usage: node scripts/check-doc-template.mjs [options]',
    '',
    '  --root <dir>       リポジトリルート (既定: このスクリプトの親ディレクトリ)',
    '  --docs <dir>       検査対象 (既定: <root>/docs)',
    '  --templates <dir>  テンプレ置き場 (既定: <root>/templates/docs)',
    '  --require-kind     kind 未設定の doc を違反として扱う (テンプレ載せ替え完了後に有効化)',
  ].join('\n');
}

function parseArgs(argv) {
  const opts = { root: REPO_ROOT, docs: null, templates: null, requireKind: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--require-kind') opts.requireKind = true;
    else if (arg === '--help' || arg === '-h') return { help: true };
    else if (arg === '--root' || arg === '--docs' || arg === '--templates') {
      const value = argv[i + 1];
      if (value === undefined || value.startsWith('--')) return { error: `${arg} に値がありません` };
      opts[arg.slice(2)] = resolve(value);
      i += 1;
    } else return { error: `不明な引数: ${arg}` };
  }
  if (opts.docs === null) opts.docs = join(opts.root, 'docs');
  if (opts.templates === null) opts.templates = join(opts.root, 'templates', 'docs');
  return { opts };
}

const isDir = (path) => existsSync(path) && statSync(path).isDirectory();

/** 生成物 (先頭行に AUTOGENERATED マーカー) は索引であって設計書ではない */
const isGenerated = (path) =>
  readFileSync(path, 'utf8').split(/\r?\n/, 1)[0].includes('AUTOGENERATED');

function listMarkdown(dir, recursive) {
  const found = [];
  const walk = (current) => {
    for (const entry of readdirSync(current, { withFileTypes: true }).sort((a, b) =>
      a.name.localeCompare(b.name),
    )) {
      const full = join(current, entry.name);
      if (entry.isDirectory()) {
        if (!recursive || SKIP_DIR.has(entry.name) || entry.name.startsWith('.')) continue;
        walk(full);
      } else if (entry.name.endsWith('.md') && entry.name !== 'README.md' && !isGenerated(full)) {
        found.push(full);
      }
    }
  };
  walk(dir);
  return found;
}

/** frontmatter の scalar と list (inline [] / ブロック -) を読む */
function parseFrontmatter(lines) {
  if (lines.length === 0 || lines[0].trim() !== '---') return null;
  let end = -1;
  for (let i = 1; i < lines.length; i += 1) {
    if (lines[i].trim() === '---') {
      end = i;
      break;
    }
  }
  if (end === -1) return null;
  const data = {};
  let listKey = null;
  for (let i = 1; i < end; i += 1) {
    const raw = lines[i].replace(/\s+#\s.*$/, '');
    const item = /^\s+-\s+(.*)$/.exec(raw);
    if (item && listKey) {
      data[listKey].push(item[1].trim().replace(/^["']|["']$/g, ''));
      continue;
    }
    const pair = /^([A-Za-z_][A-Za-z0-9_-]*):\s*(.*)$/.exec(raw);
    if (!pair) continue;
    const [, key, rest] = pair;
    const value = rest.trim();
    if (value === '') {
      listKey = key;
      data[key] = [];
      continue;
    }
    listKey = null;
    if (value.startsWith('[') && value.endsWith(']')) {
      const inner = value.slice(1, -1).trim();
      data[key] = inner === '' ? [] : inner.split(',').map((v) => v.trim().replace(/^["']|["']$/g, ''));
    } else {
      data[key] = value.replace(/^["']|["']$/g, '');
    }
  }
  return { data, bodyStart: end + 1 };
}

const normalizeHeading = (text) => text.replace(/^\d+(\.\d+)*[.．]?\s*/, '').trim();

/** コードフェンス外の H2 見出しを { text, line } で返す */
function extractSections(lines, bodyStart) {
  const sections = [];
  let inFence = false;
  for (let i = bodyStart; i < lines.length; i += 1) {
    const line = lines[i];
    if (/^\s*```/.test(line)) {
      inFence = !inFence;
      continue;
    }
    if (inFence) continue;
    const matched = /^##\s+(.*?)\s*$/.exec(line);
    if (matched) sections.push({ text: normalizeHeading(matched[1]), line: i + 1 });
  }
  return sections;
}

/** 指定 H2 節の本文行を返す */
function sectionBody(lines, sections, index) {
  const start = sections[index].line;
  const end = index + 1 < sections.length ? sections[index + 1].line - 1 : lines.length;
  return lines.slice(start, end);
}

function loadTemplates(dir) {
  const registry = new Map();
  const errors = [];
  const byPath = new Map();
  for (const file of listMarkdown(dir, true)) {
    const lines = readFileSync(file, 'utf8').split(/\r?\n/);
    const parsed = parseFrontmatter(lines);
    if (parsed === null || !parsed.data.kind) {
      errors.push(`${file} テンプレに frontmatter kind がない`);
      continue;
    }
    const { data, bodyStart } = parsed;
    const sections = extractSections(lines, bodyStart);
    const required = sections
      .filter((section) => !section.text.endsWith(OPTIONAL_SUFFIX))
      .map((section) => section.text);
    if (registry.has(data.kind)) {
      errors.push(`kind が重複: ${data.kind}`);
      continue;
    }
    registry.set(data.kind, {
      kind: data.kind,
      file,
      idPrefix: data.id_prefix ?? null,
      idPattern: data.id_pattern ?? 'numeric',
      required,
    });
    const relPath = relative(dir, file);
    const slot = dirname(relPath) === '.' ? '' : dirname(relPath);
    const name = basename(relPath);
    if (!byPath.has(slot)) byPath.set(slot, { exact: new Map(), placeholder: null });
    const entry = byPath.get(slot);
    if (/__[a-z-]+__|NNNN/.test(name)) {
      if (entry.placeholder !== null) errors.push(`${file} 同じ階層に雛形ファイルが 2 枚ある (kind を決められない)`);
      entry.placeholder = data.kind;
    } else {
      entry.exact.set(withoutSeq(name), data.kind);
    }
  }
  return { registry, byPath, errors };
}

/** ファイル名先頭の連番 (01-, 12-) を外す。連番は読む順であって種類ではないので、テンプレと番号が違っても同じ文書 */
function withoutSeq(name) {
  return name.replace(/^\d{2}-/, '');
}

/** テンプレの配置から既定 kind を引く。完全一致ファイル名 (連番抜き) > 雛形 (__name__) の順 */
function kindFromPath(byPath, docRelPath) {
  const slot = dirname(docRelPath) === '.' ? '' : dirname(docRelPath);
  const entry = byPath.get(slot);
  if (entry === undefined) return null;
  return entry.exact.get(withoutSeq(basename(docRelPath))) ?? entry.placeholder;
}

// EARS (Easy Approach to Requirements Syntax): 機能要件は
// 「<トリガ>のとき、システムは<応答>しなければならない」の形に固定する。
// 曖昧な「〜できる」「〜を考慮する」は検証不能な要件になるため落とす。
// 義務の助動詞だけを見る (「返さなければならない」「引き換えられなければならない」は可)。
// https://alistairmavin.com/ears/
const EARS_ROW_RE = /^\|\s*(REQ-1\d{2})\s*\|/;
const EARS_MODAL = 'なければならない';
function checkEars(lines, bodyStart, add) {
  for (let i = bodyStart; i < lines.length; i += 1) {
    const matched = lines[i].match(EARS_ROW_RE);
    if (!matched) continue;
    if (!lines[i].includes(EARS_MODAL)) {
      add(i + 1, `EARS 記法でない: ${matched[1]} (「<トリガ>のとき、システムは<応答>しなければならない」)`);
    }
  }
}

// ---------------------------------------------------------------------------
// arc42 12 章 (https://arc42.org/overview/) と kind の既定対応。
// 背骨を arc42 にすると決めた。章はフォルダではなく frontmatter
// `arc42: <1-12>` で表し、索引 (generate-docs-graph.mjs) が章順に並べ替える。
// null = arc42 の章を持たない文書 (arc42 の外側)。arc42 を書いていたら違反にする。
// 章 2 (Constraints) は専用文書を持たない: requirements の制約節と ADR が担う。
// ---------------------------------------------------------------------------
const ARC42_BY_KIND = new Map([
  ['requirements', 1],
  ['function-list', 1],
  ['as-is-overview', 3],
  ['solution-strategy', 4],
  ['domain-overview', 5],
  ['aggregate-map', 5],
  ['domain-model', 5],
  ['module-spec', 5],
  ['screen-spec', 5],
  ['api-spec', 5],
  ['table-spec', 5],
  ['business-flow', 6],
  ['sequence-spec', 6],
  ['state-machine', 6],
  ['job', 6],
  ['infra-design', 7],
  ['operations', 7],
  ['migration-plan', 7],
  ['crosscutting', 8],
  ['code-definitions', 8],
  ['messages', 8],
  ['permission-matrix', 8],
  ['i18n', 8],
  ['adr', 9],
  ['nonfunctional', 10],
  ['test-plan', 10],
  ['test-spec', 10],
  ['risks-tech-debt', 11],
  ['glossary', 12],
  // arc42 の外側: 実装手順 (spec-kit 由来) と対外文書・解説
  ['tasks', null],
  ['proposal', null],
  ['guide', null],
  ['implementation-order', null],
  ['explanation', null],
  ['runbook', null],
]);

function checkArc42(kind, data, add, requireKind) {
  if (!ARC42_BY_KIND.has(kind)) {
    add(1, `arc42 章の既定が未登録の kind: ${kind} (scripts/check-doc-template.mjs の ARC42_BY_KIND に足す)`);
    return;
  }
  const expected = ARC42_BY_KIND.get(kind);
  const declared = data.arc42 === undefined ? null : Number(data.arc42);
  if (expected === null) {
    if (declared !== null) add(1, `arc42 章を持たない kind: ${kind} (frontmatter の arc42 を消す)`);
    return;
  }
  if (declared === null) {
    if (requireKind) add(1, `frontmatter に arc42 がない (kind: ${kind} の既定は ${expected})`);
    return;
  }
  if (declared !== expected) {
    add(1, `arc42 章が kind の既定と食い違う: frontmatter=${data.arc42} / kind ${kind} の既定=${expected}`);
  }
}

function checkDoc(file, lines, meta, template, idIndex, rel, requireKind) {
  const violations = [];
  const { data, bodyStart } = meta;
  const add = (line, message) => violations.push(`${rel(file)}:${line} ${message}`);

  const opener = /^>\s*\*\*(TL;DR|When to use)/;
  const hasOpener = lines.slice(bodyStart).some((line) => opener.test(line));
  if (!hasOpener) add(bodyStart + 1, 'TL;DR / When to use ブロックがない');

  const sections = extractSections(lines, bodyStart);
  const texts = sections.map((section) => section.text);
  for (const requiredText of template.required) {
    const found = texts.some((text) => text.startsWith(requiredText));
    if (!found) add(bodyStart + 1, `必須の節がない: ## ${requiredText}`);
  }

  const relatedIndex = sections.findIndex((section) => section.text.startsWith('関連'));
  if (relatedIndex === -1) {
    add(bodyStart + 1, '「関連」節がない (上流/下流の表が必須)');
  } else {
    const body = sectionBody(lines, sections, relatedIndex);
    const entries = [];
    for (const line of body) {
      const trimmed = line.trim();
      if (trimmed.startsWith('|') && !/^\|[\s|:-]+\|$/.test(trimmed)) {
        const cells = trimmed.split('|').map((cell) => cell.trim());
        entries.push({ label: cells[1] ?? '', value: cells[2] ?? '' });
        continue;
      }
      const bullet = trimmed.match(/^[-*]\s+(.+?)\s*[:：]\s*(.*)$/);
      if (bullet) entries.push({ label: bullet[1], value: bullet[2] });
    }
    const hasFilledRow = (keyword) =>
      entries.some((entry) => entry.label.includes(keyword) && entry.value.replace(/[\s—-]/g, '') !== '');
    if (!hasFilledRow('上流')) add(sections[relatedIndex].line, '「関連」節に上流の行がない (空欄不可)');
    if (!hasFilledRow('下流')) add(sections[relatedIndex].line, '「関連」節に下流の行がない (空欄不可)');
  }

  if (template.idPattern === 'class-name') {
    if (!data.code_root) add(1, 'frontmatter に code_root がない (図↔実装照合に必須)');
  } else if (template.idPrefix) {
    // bare-numeric = T001 形式 (spec-kit の tasks)。既定は PREFIX-nnn。
    const bare = template.idPattern === 'bare-numeric';
    const pattern = bare
      ? new RegExp(`\\b${template.idPrefix}\\d[0-9A-Za-z_-]*`, 'g')
      : new RegExp(`\\b${template.idPrefix}-[A-Za-z0-9_-]+`, 'g');
    const strict = bare
      ? new RegExp(`^${template.idPrefix}\\d{3}$`)
      : new RegExp(`^${template.idPrefix}-\\d{3}$`);
    let count = 0;
    for (let i = bodyStart; i < lines.length; i += 1) {
      for (const token of lines[i].match(pattern) ?? []) {
        count += 1;
        if (!strict.test(token)) {
          const shape = bare ? `${template.idPrefix}nnn` : `${template.idPrefix}-nnn`;
          add(i + 1, `ID 形式が不正: ${token} (${shape} の 3 桁)`);
        }
      }
    }
    if (count === 0) {
      add(bodyStart + 1, `${bare ? template.idPrefix : `${template.idPrefix}-`}nnn の ID が 1 件もない`);
    }
  }

  if (template.kind === 'requirements') checkEars(lines, bodyStart, add);

  checkArc42(template.kind, data, add, requireKind);

  const dependsOn = Array.isArray(data.depends_on) ? data.depends_on : [];
  for (const dependency of dependsOn) {
    if (dependency.startsWith('external:')) continue;
    if (!idIndex.has(dependency)) {
      add(1, `depends_on が存在しない id を指している: ${dependency}`);
    }
  }
  return violations;
}

function run(argv) {
  const parsed = parseArgs(argv);
  if (parsed.help) {
    process.stdout.write(`${usage()}\n`);
    return EXIT_OK;
  }
  if (parsed.error) {
    process.stderr.write(`CONFIG ${parsed.error}\n\n${usage()}\n`);
    return EXIT_CANNOT_CHECK;
  }
  const { root, docs, templates, requireKind } = parsed.opts;
  const rel = (path) => relative(root, path) || path;

  if (!isDir(templates)) {
    process.stderr.write(`CONFIG テンプレ置き場が無い: ${rel(templates)}\n`);
    return EXIT_CANNOT_CHECK;
  }
  if (!isDir(docs)) {
    process.stderr.write(`CONFIG docs が無い: ${rel(docs)}\n`);
    return EXIT_CANNOT_CHECK;
  }
  const { registry, byPath, errors } = loadTemplates(templates);
  if (errors.length > 0) {
    for (const message of errors) process.stderr.write(`CONFIG ${message}\n`);
    return EXIT_CANNOT_CHECK;
  }
  if (registry.size === 0) {
    process.stderr.write(`CONFIG テンプレが 1 枚も無い: ${rel(templates)}\n`);
    return EXIT_CANNOT_CHECK;
  }

  const files = listMarkdown(docs, true);
  const parsedDocs = [];
  const idIndex = new Map();
  for (const file of files) {
    const lines = readFileSync(file, 'utf8').split(/\r?\n/);
    const meta = parseFrontmatter(lines);
    parsedDocs.push({ file, lines, meta });
    if (meta?.data.id) idIndex.set(meta.data.id, file);
  }

  const violations = [];
  const unmanaged = [];
  let managed = 0;

  for (const { file, lines, meta } of parsedDocs) {
    if (meta === null) {
      // frontmatter 自体の検査は generate-docs-graph.mjs 側の担当。ここでは kind 未設定と同じ扱いにする
      unmanaged.push(rel(file));
      continue;
    }
    const pathKind = kindFromPath(byPath, relative(docs, file));
    const declared = meta.data.kind ?? null;
    if (declared !== null && pathKind !== null && declared !== pathKind) {
      violations.push(
        `${rel(file)}:1 kind と置き場所が食い違う: frontmatter=${declared} / 配置=${pathKind}`,
      );
      continue;
    }
    const kind = declared ?? pathKind;
    if (!kind) {
      unmanaged.push(rel(file));
      continue;
    }
    const template = registry.get(kind);
    if (!template) {
      violations.push(
        `${rel(file)}:1 未登録の kind: ${kind} (templates/docs にテンプレを作るか kind を直す)`,
      );
      continue;
    }
    managed += 1;
    violations.push(...checkDoc(file, lines, meta, template, idIndex, rel, requireKind));
  }

  for (const path of unmanaged) {
    process.stdout.write(`TODO  ${path} kind 未設定 (frontmatter にも無く、置き場所にテンプレも無い)\n`);
  }
  if (requireKind && unmanaged.length > 0) {
    for (const path of unmanaged) violations.push(`${path}:1 kind を決められない (frontmatter kind か、テンプレのある階層への移動が要る)`);
  }
  if (violations.length > 0) {
    for (const message of violations.sort()) process.stderr.write(`NG    ${message}\n`);
    process.stderr.write(`\nNG    ${violations.length} 件。テンプレは ${rel(templates)}。\n`);
    return EXIT_VIOLATION;
  }
  process.stdout.write(
    `OK    kind 登録 ${registry.size} 種 / 検査 ${managed} 本 / kind 未設定 ${unmanaged.length} 本\n`,
  );
  return EXIT_OK;
}

process.exit(run(process.argv.slice(2)));
