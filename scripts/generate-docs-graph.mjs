#!/usr/bin/env node
/**
 * Generate docs/dependencies.md + the ADR index table, validate frontmatter,
 * and enforce referential integrity — all from frontmatter in docs/**\/*.md.
 *
 * Reads YAML frontmatter (id, title, type, status, relates_to, depends_on,
 * supersedes, superseded_by, canonical, canonical_for) from every Markdown
 * file under docs/, and:
 *   1. validates the frontmatter schema (type-aware; ADR is strict)
 *   2. enforces referential integrity (every ADR reference must resolve)
 *   3. auto-generates docs/dependencies.md (Mermaid graph + tables)
 *   4. auto-generates the ADR index table in docs/adr/README.md
 *   5. auto-generates a per-directory index (AUTOGEN:dir-index) in every docs/**\/README.md;
 *      --check fails if a README is missing or a doc is not listed (no orphan docs)
 *
 * Usage:
 *   node scripts/generate-docs-graph.mjs              # write, fail on hard error
 *   node scripts/generate-docs-graph.mjs --check      # CI: fail on drift OR hard error
 *   node scripts/generate-docs-graph.mjs --write      # write generated files
 *
 * Spec: docs/guides/document-taxonomy.md
 */

