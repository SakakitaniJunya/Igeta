async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (e) => {
      const p = join(dir, e.name);
      if (e.isDirectory()) return walk(p);
      if (e.isFile() && p.endsWith(".md")) return [p];
      return [];
    }),
  );
  return files.flat();
}

function parseFrontmatter(content) {
  if (!content.startsWith("---\n")) return null;
  const end = content.indexOf("\n---\n", 4);
  if (end < 0) return null;
  const yaml = content.slice(4, end);
  const fm = {};
  let currentKey = null;
  for (const line of yaml.split("\n")) {
    if (!line.trim()) continue;
    if (line.startsWith("  - ") && currentKey) {
      fm[currentKey] = fm[currentKey] || [];
      // strip inline comments after the value
      fm[currentKey].push(line.slice(4).replace(/\s+#.*$/, "").trim());
      continue;
    }
    // 数字を含むキー (arc42) も拾う。[a-z_]+ だけだと arc42 が無言で落ちる
    const m = line.match(/^([a-z_][a-z0-9_]*):\s*(.*)$/);
    if (!m) continue;
    const [, key, raw] = m;
    currentKey = key;
    // strip inline comments (e.g. "id: foo   # note")
    const value = raw.replace(/\s+#.*$/, "").trim();
    if (value === "" || value === "[]") {
      fm[key] = value === "[]" ? [] : "";
    } else if (value.startsWith("[") && value.endsWith("]")) {
      fm[key] = value
        .slice(1, -1)
        .split(",")
        .map((s) => s.trim())
        .filter(Boolean);
    } else {
      fm[key] = value;
    }
  }
  return fm;
}

function escapeId(s) {
  return String(s).replace(/[^a-zA-Z0-9_-]/g, "_");
}

function nodeLabel(doc) {
  const status = doc.status && doc.status !== "active" ? ` (${doc.status})` : "";
  return `${doc.title}${status}`;
}

function indexById(docs) {
  const byId = new Map();
  const dupes = [];
  for (const d of docs) {
    if (!d.id) continue;
    if (byId.has(d.id)) {
      dupes.push({ id: d.id, paths: [byId.get(d.id).path, d.path] });
    } else {
      byId.set(d.id, d);
    }
  }
  if (dupes.length > 0) {
    const lines = dupes
      .map((x) => `  - id="${x.id}": ${x.paths.join(" / ")}`)
      .join("\n");
    throw new Error(
      `[docs-graph] frontmatter id 重複検出:\n${lines}\n\n対処: いずれかの doc を rename or supersede し、id を一意化してください。`,
    );
  }
  return byId;
}

// `aliases:` (docs-structure.md「旧 path/id (rename 後の link 救済)」) の索引。
// doc を rename すると旧 id は byId から消えるため、`supersedes:` のように
// **retired id を指す参照が恒久 warning になる**。実測 (2026-09-03): 6 分冊の
// rename で warning が 1 → 7 件に増え、実在の 1 件が埋もれた。
// alias を解決対象に含めることで「typo/対象消失は検出しつつ、意図した retire は
// 黙る」を両立する。alias は **byId には入れない** — グラフのノード/エッジは
// 現存 doc だけで構成し、自己ループを作らないため。
function indexAliases(docs, byId) {
  const byAlias = new Map();
  const conflicts = [];
  for (const d of docs) {
    for (const a of d.aliases || []) {
      // alias が現存 id を覆い隠すと、本物の dangling ref が見えなくなる
      if (byId.has(a)) conflicts.push(`  - alias="${a}" は現存 doc の id と衝突 (${d.path})`);
      else if (byAlias.has(a)) conflicts.push(`  - alias="${a}" が重複: ${byAlias.get(a).path} / ${d.path}`);
      else byAlias.set(a, d);
    }
  }
  if (conflicts.length > 0) {
    throw new Error(
      `[docs-graph] aliases の衝突検出:\n${conflicts.join("\n")}\n\n` +
        `対処: alias は「もう存在しない旧 id」にのみ使い、現存 id と重複させないでください。`,
    );
  }
  return byAlias;
}

// ADR 番号の一意性。indexById() は frontmatter `id` の完全一致しか見ないため、
// `0029-a.md` と `0029-b.md` のように **id は違うが 4 桁番号が衝突する** ケースを
// 素通りさせる (2026-09-03 実測: 並行セッションが同時刻に 0029 を採番し、
// docs/adr/README.md に「0029」の行が 2 本並んだまま --check が exit 0 で通った)。
// ADR 番号は決定の一次識別子であり、重複は「どちらの ADR-0029 か」を破壊するため
// id 重複と同格の hard error として扱う。
function assertUniqueAdrNumbers(docs) {
  const byNumber = new Map();
  for (const d of docs) {
    // ファイル名の 4 桁 prefix を見る。frontmatter id ではなく **ファイル名**が
    // 索引・相互リンク・人間の呼称 (「ADR-0029」) の実体だから。
    const file = basename(d.path);
    const m = file.match(/^(\d{4})-/);
    if (!m || !d.path.includes("/adr/")) continue;
    const n = m[1];
    if (!byNumber.has(n)) byNumber.set(n, []);
    byNumber.get(n).push(d.path);
  }
  const dupes = [...byNumber.entries()].filter(([, paths]) => paths.length > 1);
  if (dupes.length > 0) {
    const lines = dupes
      .map(([n, paths]) => `  - ADR-${n}: ${paths.join(" / ")}`)
      .join("\n");
    throw new Error(
      `[docs-graph] ADR 番号の重複検出:\n${lines}\n\n` +
        `対処: 後から採番された方を空き番号へ rename し、frontmatter id と\n` +
        `被参照 (docs/ .claude/ 内の grep) をセットで更新してください。\n` +
        `採番前の空き確認は grep -rn "<番号>-" .claude/ docs/ で行うこと\n` +
        `(ls と git log --all は未 commit の予約を検出できない)。`,
    );
  }
}

// ---------------------------------------------------------------------------
// Validation: schema (§13.1) + referential integrity (§13.7)
// Returns { errors: string[], warnings: string[] }.
// ADR docs are validated strictly (violations are errors); other docs warn.
// ---------------------------------------------------------------------------
function validate(docs, byId, byAlias = new Map()) {
  const errors = [];
  const warnings = [];
  // An ADR *decision* doc has a numbered id (adr-NNNN-…). The ADR index
  // (id: adr-index) and other index-like docs are not decisions and are not
  // held to the ADR lifecycle schema.
  const isAdrDecision = (d) => /^adr-\d{4}/.test(d.id || "");

  // Schema validation is ADR-strict only. The broader docs corpus uses a much
  // richer status vocabulary (vision/fixed/deferred/…); validating it here
  // would be noise outside ADR scope. Referential integrity (below) still runs
  // corpus-wide because dangling refs are always a real defect.
  for (const d of docs) {
    if (!isAdrDecision(d)) continue;
    const tag = `${d.id} (${d.path})`;
    // required keys
    for (const key of ["id", "title", "type", "status"]) {
      if (!d[key]) errors.push(`[schema] ${tag}: 必須 frontmatter \`${key}\` が無い`);
    }
    // status enum (ADR lifecycle)
    if (d.status && !ADR_STATUSES.has(d.status)) {
      errors.push(
        `[schema] ${tag}: status="${d.status}" は許可外 (adr: ${[...ADR_STATUSES].join("|")})`,
      );
    }
    // canonical:false ⇒ canonical_for 必須
    if (d.canonical === "false" && !d.canonical_for) {
      errors.push(`[schema] ${tag}: canonical:false だが canonical_for が無い`);
    }
  }

  // referential integrity: every referenced id must resolve.
  // Hard error when the SOURCE is an ADR or the TARGET is an adr-* id
  // (ADRs are append-only contracts and must never dangle). Otherwise warn.
  for (const d of docs) {
    const refs = [];
    for (const f of REF_FIELDS) for (const t of d[f] || []) refs.push([f, t]);
    if (d.superseded_by) refs.push(["superseded_by", d.superseded_by]);
    if (d.canonical_for) refs.push(["canonical_for", d.canonical_for]);
    for (const [field, target] of refs) {
      // retired id は aliases: で救済済みなら解決とみなす (typo は救済されない)
      if (byId.has(target) || byAlias.has(target)) continue;
      const msg = `[ref] ${d.id} (${d.path}) .${field} → "${target}" が解決できない`;
      const hard = d.type === "adr" || /^adr-\d{4}/.test(target);
      (hard ? errors : warnings).push(msg);
    }
  }

  return { errors, warnings };
}

function buildMermaid(docs, byId) {
  const lines = [];
  lines.push("```mermaid");
  lines.push("graph LR");
  lines.push("  classDef standard fill:#fde68a,stroke:#92400e,color:#111");
  lines.push("  classDef architecture fill:#bfdbfe,stroke:#1e3a8a,color:#111");
  lines.push("  classDef strategy fill:#fbcfe8,stroke:#9d174d,color:#111");
  lines.push("  classDef prd fill:#bbf7d0,stroke:#065f46,color:#111");
  lines.push("  classDef business fill:#a7f3d0,stroke:#064e3b,color:#111");
  lines.push("  classDef adr fill:#c7d2fe,stroke:#3730a3,color:#111");
  lines.push("  classDef runbook fill:#fecaca,stroke:#7f1d1d,color:#111");
  lines.push("  classDef guide fill:#e9d5ff,stroke:#581c87,color:#111");
  lines.push("  classDef design fill:#ddd6fe,stroke:#6d28d9,color:#111");

  for (const d of docs) {
    const id = escapeId(d.id);
    const label = nodeLabel(d).replace(/"/g, "'");
    lines.push(`  ${id}["${label}"]`);
    if (d.type) lines.push(`  class ${id} ${escapeId(d.type)}`);
  }

  // depends_on edges (solid arrow): upstream --> downstream
  for (const d of docs) {
    for (const up of d.depends_on || []) {
      if (!byId.has(up)) continue;
      lines.push(`  ${escapeId(up)} ==> ${escapeId(d.id)}`);
    }
  }
  // relates_to edges (dotted, undirected — render one direction to avoid dup)
  const seen = new Set();
  for (const d of docs) {
    for (const rel of d.relates_to || []) {
      if (!byId.has(rel)) continue;
      const key = [d.id, rel].sort().join("|");
      if (seen.has(key)) continue;
      seen.add(key);
      lines.push(`  ${escapeId(d.id)} -.- ${escapeId(rel)}`);
    }
  }
  // supersede edges
  for (const d of docs) {
    for (const old of d.supersedes || []) {
      if (!byId.has(old)) continue;
      lines.push(`  ${escapeId(old)} -. supersedes .-> ${escapeId(d.id)}`);
    }
  }

  lines.push("```");
  return lines.join("\n");
}

function buildSupersedeTable(docs) {
  const rows = [];
  for (const d of docs) {
    if (d.superseded_by) {
      rows.push({ from: d.id, to: d.superseded_by, status: d.status });
    }
  }
  if (rows.length === 0) return null;
  return [
    "| 旧 ID | 新 ID | 旧 Status |",
    "|---|---|---|",
    ...rows.map((r) => `| ${r.from} | ${r.to} | ${r.status} |`),
  ].join("\n");
}

function buildOrphans(docs) {
  const referenced = new Set();
  for (const d of docs) {
    for (const r of d.relates_to || []) referenced.add(r);
    for (const r of d.depends_on || []) referenced.add(r);
    for (const r of d.supersedes || []) referenced.add(r);
    if (d.superseded_by) referenced.add(d.superseded_by);
  }
  const orphans = docs.filter(
    (d) =>
      !referenced.has(d.id) &&
      (!d.relates_to || d.relates_to.length === 0) &&
      (!d.depends_on || d.depends_on.length === 0),
  );
  if (orphans.length === 0) return null;
  return [
    "| ID | Type | Path |",
    "|---|---|---|",
    ...orphans.map(
      (d) => `| ${d.id} | ${d.type || "?"} | [\`${d.path}\`](${d.path.replace(/^docs\//, "")}) |`,
    ),
  ].join("\n");
}

function buildIndex(docs) {
  const grouped = new Map();
  for (const d of docs) {
    const t = d.type || "other";
    if (!grouped.has(t)) grouped.set(t, []);
    grouped.get(t).push(d);
  }
  const order = [
    "standard", "strategy", "architecture", "adr", "design",
    "prd", "guide", "runbook", "explanation", "business", "other",
  ];
  const lines = [];
  for (const t of order) {
    const list = grouped.get(t);
    if (!list || list.length === 0) continue;
    list.sort((a, b) => a.id.localeCompare(b.id));
    lines.push(`### ${t}`);
    lines.push("");
    for (const d of list) {
      const status = d.status && d.status !== "active" ? ` _(${d.status})_` : "";
      lines.push(`- **${d.id}**${status} — [${d.title}](${d.path.replace(/^docs\//, "")})`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

// Build the "未解決参照 (warn)" section so non-ADR dangling refs stay visible.
function buildUnresolvedSection(warnings) {
  const refWarns = warnings.filter((w) => w.startsWith("[ref]"));
  if (refWarns.length === 0) return null;
  return [
    "## ⚠️ 未解決参照 (warn — Phase 1 で error 昇格予定)",
    "",
    "frontmatter の参照先 id が存在しない箇所。ADR 起因は CI block (error)、それ以外は警告として可視化する。",
    "",
    ...refWarns.map((w) => `- ${w.replace(/^\[ref\] /, "")}`),
  ].join("\n");
}

// ---------------------------------------------------------------------------
// ADR index table — auto-generated into docs/adr/README.md between AUTOGEN markers.
// ---------------------------------------------------------------------------
function adrNumber(id) {
  const m = String(id).match(/adr-(\d{4})/);
  return m ? m[1] : null;
}

function buildAdrIndexTable(docs) {
  const adrs = docs
    .filter((d) => d.type === "adr" && adrNumber(d.id) && d.status !== "template")
    .sort((a, b) => adrNumber(a.id).localeCompare(adrNumber(b.id)));
  const lines = [
    "| # | タイトル | Status | proposed | accepted |",
    "|---|---|---|---|---|",
  ];
  for (const d of adrs) {
    const n = adrNumber(d.id);
    const file = basename(d.path);
    const accepted = !d.accepted || d.accepted === "null" ? "—" : d.accepted;
    const proposed = d.proposed || d.adopted || "—";
    // escape pipe chars in titles so the table doesn't break
    const title = String(d.title).replace(/\|/g, "\\|");
    lines.push(`| [${n}](${file}) | ${title} | ${d.status} | ${proposed} | ${accepted} |`);
  }
  return lines.join("\n");
}

function spliceAdrReadme(existing, table) {
  const startIdx = existing.indexOf(ADR_INDEX_START);
  const endIdx = existing.indexOf(ADR_INDEX_END);
  if (startIdx < 0 || endIdx < 0 || endIdx < startIdx) {
    throw new Error(
      `[docs-graph] ${ADR_README_REL} に AUTOGEN マーカーが無い。\n` +
        `  ${ADR_INDEX_START}\n  ...\n  ${ADR_INDEX_END}\n` +
        `を ADR 一覧表の前後に置いてください。`,
    );
  }
  const before = existing.slice(0, startIdx + ADR_INDEX_START.length);
  const after = existing.slice(endIdx);
  return `${before}\n\n${table}\n\n${after}`;
}

// ---------------------------------------------------------------------------
// Per-directory README index — every non-README doc must be listed in its own
// directory's README between AUTOGEN markers (docs-structure.md サブディレクトリ 3 ルール 4).
// --check fails when a README is missing or its index region is stale, so a doc
// cannot be "作るだけ作られる" without showing up in navigation.
// ---------------------------------------------------------------------------
const DIR_INDEX_START = "<!-- AUTOGEN:dir-index:start — generated by scripts/generate-docs-graph.mjs, do not edit by hand -->";
const DIR_INDEX_END = "<!-- AUTOGEN:dir-index:end -->";

// arc42 12 章 (https://arc42.org/overview/)。英語名は公式、日本語は訳。
// 索引はフォルダ順ではなく **章順** に並べる — 設計書の背骨が arc42 だから。
const ARC42_CHAPTERS = [
  [1, "Introduction and Goals", "導入と目標"],
  [2, "Constraints", "制約"],
  [3, "Context and Scope", "コンテキストと範囲"],
  [4, "Solution Strategy", "解決戦略"],
  [5, "Building Block View", "構成要素"],
  [6, "Runtime View", "実行時ビュー"],
  [7, "Deployment View", "配置ビュー"],
  [8, "Crosscutting Concepts", "横断概念"],
  [9, "Architecture Decisions", "アーキテクチャ決定"],
  [10, "Quality Requirements", "品質要求"],
  [11, "Risks and Technical Debt", "リスクと技術的負債"],
  [12, "Glossary", "用語集"],
];
// arc42 の外側にある文書種別 (章が無いのが正しい)。章未割当の警告対象から外す。
const NON_ARC42_KINDS = new Set(["tasks", "proposal", "guide", "explanation", "runbook"]);

function firstHeading(content) {
  const m = content.match(/^#\s+(.+)$/m);
  return m ? m[1].trim() : null;
}
function cell(v) {
  return String(v ?? "—").replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");
}

function spliceDirReadme(dir, existing, table) {
  const block = `${DIR_INDEX_START}\n\n${table}\n\n${DIR_INDEX_END}`;
  if (existing == null) {
    const slug = relative(DOCS_DIR, dir).replace(/[\\/]/g, "-") || "docs";
    return [
      "---", `id: ${slug}-index`, `title: ${basename(dir)} — 索引`, "type: index", "status: active", "owners: [eng]", "---", "",
      `# ${basename(dir)}`, "",
      "> このディレクトリの目的: (要記入)",
      "",
      "## 索引", "", block, "",
    ].join("\n");
  }
  const st = existing.indexOf(DIR_INDEX_START);
  const en = existing.indexOf(DIR_INDEX_END);
  if (st >= 0 && en > st) return `${existing.slice(0, st)}${block}${existing.slice(en + DIR_INDEX_END.length)}`;
  return `${existing.trimEnd()}\n\n## 索引\n\n${block}\n`;
}

/**
 * arc42 章別の索引。docs/ と docs/design/ の README はフォルダ順ではなくこの形で出す。
 * 1 章 = 1 行 (README 60 行上限を守るため)。章に文書が無ければ「未作成」と書き、
 * 穴がそのまま TODO に見えるようにする。
 */
function buildArc42Table(from, entries, meta, arc42Warnings, elsewhereDocs = []) {
  const byChapter = new Map(ARC42_CHAPTERS.map(([n]) => [n, []]));
  const outside = [];
  const unassigned = [];
  for (const f of entries) {
    const { fm, title, content } = meta.get(f);
    const link = `[${cell(title)}](${relative(from, f).split(sep).join("/")})`;
    // 生成物 (dependencies.md 等) は設計書ではないので章を持たない。警告もしない。
    if (content.startsWith("<!-- AUTOGENERATED")) { outside.push(link); continue; }
    const chapter = fm.arc42 === undefined ? null : Number(fm.arc42);
    if (chapter !== null && byChapter.has(chapter)) byChapter.get(chapter).push(link);
    else if (chapter !== null) unassigned.push(link);
    else if (NON_ARC42_KINDS.has(fm.kind)) outside.push(link);
    else {
      unassigned.push(link);
      arc42Warnings.push(`${relative(ROOT, f)} に frontmatter arc42 が無い (章未割当。kind: ${fm.kind ?? "—"})`);
    }
  }
  // このディレクトリ配下に無い章でも、他所 (product/ adr/ architecture/ 等) に実在することがある。
  // その場合は「未作成」ではなく、実在する側のディレクトリ README へのリンクを 1 個出す。
  // 本当に 1 本も無い章だけを _未作成_ と書く (穴を穴として見せるため)。
  const elsewhereByChapter = new Map(ARC42_CHAPTERS.map(([n]) => [n, new Set()]));
  for (const f of elsewhereDocs) {
    const entry = meta.get(f);
    if (!entry || entry.content.startsWith("<!-- AUTOGENERATED")) continue;
    const chapter = entry.fm.arc42 === undefined ? null : Number(entry.fm.arc42);
    if (chapter === null || !elsewhereByChapter.has(chapter)) continue;
    const dir = dirname(f);
    const rel = relative(from, join(dir, "README.md")).split(sep).join("/");
    const label = `${relative(DOCS_DIR, dir).split(sep).join("/") || "docs"}/`;
    elsewhereByChapter.get(chapter).add(`→ [${label}](${rel})`);
  }
  const rows = ARC42_CHAPTERS.map(([n, en, ja]) => {
    const docs = byChapter.get(n);
    const other = [...elsewhereByChapter.get(n)].sort();
    const cellText = [...docs, ...other].join(" · ") || "_未作成_";
    return `| **§${n} ${en}** (${ja}) | ${cellText} |`;
  });
  if (outside.length) rows.push(`| arc42 章外 (tutorial / guide / explanation / proposal / runbook / tasks) | ${outside.join(" · ")} |`);
  if (unassigned.length) rows.push(`| **章未割当** (frontmatter に arc42 が無い) | ${unassigned.join(" · ")} |`);
  return ["| arc42 章 | 文書 |", "|---|---|", ...rows].join("\n");
}

async function buildDirIndexes(allFilesRaw, overrides = new Map()) {
  let allFiles = allFilesRaw;
  // overrides: path -> content to use instead of disk (ADR README after the ADR-index splice,
  // and the previous pass's generated READMEs) so that --write is idempotent in one run.
  const meta = new Map();
  const readOrOverride = async (f) => (overrides.has(f) ? overrides.get(f) : readFile(f, "utf8").catch(() => null));
  for (const f of new Set([...allFiles, ...overrides.keys()])) {
    const content = await readOrOverride(f);
    if (content == null) continue;
    const fm = parseFrontmatter(content) || {};
    meta.set(f, { fm, content, title: fm.title || firstHeading(content) || basename(f, ".md") });
  }
  const isReadme = (f) => basename(f).toLowerCase() === "readme.md";
  // dependencies.md は本スクリプトの生成物。索引に載せると「1 回目の --write では
  // まだ存在せず、2 回目で行が増える」= --write 直後の --check が落ちる不動点崩れになる。
  // 本文から直接リンクされているので索引からは外す。
  allFiles = allFiles.filter((f) => f !== OUTPUT);
  const own = new Map(); // dir -> own non-README md files
  const children = new Map(); // dir -> Set(child dirs)
  for (const f of allFiles) {
    if (!isReadme(f)) { if (!own.has(dirname(f))) own.set(dirname(f), []); own.get(dirname(f)).push(f); }
    let d = dirname(f);
    while (d !== DOCS_DIR) { const parent = dirname(d); if (!children.has(parent)) children.set(parent, new Set()); children.get(parent).add(d); d = parent; }
  }
  // a directory gets its own README index iff it directly holds a doc (or is the docs root)
  const indexed = (d) => d === DOCS_DIR || (own.get(d) || []).length > 0;
  const descendantRows = (from, d) => {
    const rows = [];
    for (const c of [...(children.get(d) || [])].sort()) {
      if (indexed(c)) {
        const relDir = relative(from, c);
        const t = meta.get(join(c, "README.md"))?.title || `${basename(c)} — 索引`;
        rows.push(`| [${relDir}/](${relDir}/README.md) | ${cell(t)} | dir | — |`);
      } else {
        rows.push(...descendantRows(from, c)); // pass-through dir: list its indexed descendants
      }
    }
    return rows;
  };
  // 章別索引を出すディレクトリ。配下の全文書を arc42 章順に並べる。
  const CHAPTER_DIRS = [DOCS_DIR, join(DOCS_DIR, "design")];
  const descendantDocs = (d) => allFiles.filter((f) => !isReadme(f) && (f.startsWith(d + sep)));
  const results = [];
  const arc42Warnings = [];
  for (const dir of [...new Set([DOCS_DIR, ...CHAPTER_DIRS, ...own.keys()])].sort((a, b) => a.localeCompare(b))) {
    const isChapterDir = CHAPTER_DIRS.includes(dir);
    if (!indexed(dir) && !isChapterDir) continue;
    const readmePath = join(dir, "README.md");
    const isAdrDir = dir === join(DOCS_DIR, "adr");
    const rows = descendantRows(dir, dir);
    const entries = (own.get(dir) || [])
      // docs/adr: numbered ADRs are already listed in the ADR index table above
      .filter((f) => !(isAdrDir && meta.get(f).fm.type === "adr" && adrNumber(meta.get(f).fm.id) && meta.get(f).fm.status !== "template"))
      .sort();
    for (const f of entries) {
      const { fm, title } = meta.get(f);
      rows.push(`| [${basename(f)}](${basename(f)}) | ${cell(title)} | ${cell(fm.type || "—")} | ${cell(fm.status || "—")} |`);
    }
    const table = isChapterDir
      ? buildArc42Table(
          dir,
          descendantDocs(dir).sort(),
          meta,
          arc42Warnings,
          allFiles.filter((f) => !isReadme(f) && !f.startsWith(dir + sep)).sort(),
        )
      : ["| ファイル | タイトル | type | status |", "|---|---|---|---|", ...rows].join("\n");
    if (!isChapterDir && rows.length === 0) continue;
    // `existing` は常にディスクの実体を見る。overrides (pass1 の desired) を existing に使うと
    // pass2 で existing === desired となり --write が索引を書かず --check も drift を見逃す
    // (2026-09-11 gotcha: 新規/改名 doc の AUTOGEN 索引取りこぼし の根本原因)。
    const existing = await readFile(readmePath, "utf8").catch(() => null);
    results.push({ readmePath, rel: relative(ROOT, readmePath), existing, desired: spliceDirReadme(dir, existing, table) });
  }
  results.arc42Warnings = arc42Warnings;
  return results;
}

async function main() {
  const arg = process.argv[2];
  const allFiles = await walk(DOCS_DIR);
  const docs = [];
  for (const f of allFiles) {
    if (f === OUTPUT) continue;
    const rel = relative(ROOT, f);
    const content = await readFile(f, "utf8");
    const fm = parseFrontmatter(content);
    if (!fm || !fm.id) continue;
    docs.push({ ...fm, path: rel });
  }
  docs.sort((a, b) => a.id.localeCompare(b.id));

  const byId = indexById(docs); // throws on duplicate id
  assertUniqueAdrNumbers(docs); // throws on duplicate ADR number (id 一致でなくても検出)
  const byAlias = indexAliases(docs, byId); // throws on alias/id collision
  const { errors, warnings } = validate(docs, byId, byAlias);

  // ---- generate dependencies.md content ----
  const mermaid = buildMermaid(docs, byId);
  const supersede = buildSupersedeTable(docs);
  const orphans = buildOrphans(docs);
  const index = buildIndex(docs);
  const unresolved = buildUnresolvedSection(warnings);
  const now = new Date().toISOString().split("T")[0];
  const depsOut = [
    "<!-- AUTOGENERATED BY scripts/generate-docs-graph.mjs — DO NOT EDIT BY HAND -->",
    "",
    "# Docs 依存関係グラフ",
    "",
    `> 自動生成: ${now} (UTC) / ソース: 各 \`docs/**/*.md\` の frontmatter`,
    `> 規約: docs/guides/document-taxonomy.md 参照`,
    `> 再生成: \`node scripts/generate-docs-graph.mjs --write\``,
    "",
    "## 凡例",
    "",
    "- **太矢印 `==>`**: `depends_on` (上流 → 下流、上流が変わったら下流レビュー必須)",
    "- **点線 `-.-`**: `relates_to` (双方向、緩い結び)",
    "- **点線矢印 `-. supersedes .->`**: 旧 → 新 (ADR の置き換え)",
    "- ノード色は `type` を表す (standard / architecture / strategy / prd / business / adr / runbook / guide / design)",
    "",
    "## グラフ",
    "",
    mermaid,
    "",
    "## ドキュメント一覧 (type 別)",
    "",
    index,
    supersede ? "## Supersede チェーン\n\n" + supersede + "\n" : "",
    unresolved ? unresolved + "\n" : "",
    orphans
      ? "## 孤立ドキュメント (誰からも参照されていない)\n\n" + orphans + "\n"
      : "## 孤立ドキュメント\n\n_該当なし_\n",
  ]
    .filter(Boolean)
    .join("\n");

  // ---- generate ADR README index ----
  const adrTable = buildAdrIndexTable(docs);
  const adrExisting = await readFile(ADR_README, "utf8");
  const adrOut = spliceAdrReadme(adrExisting, adrTable);

  // ---- per-directory README indexes ----
  // two passes: pass 2 sees the READMEs pass 1 would create/update (titles of new stubs, ADR splice),
  // so the output is a fixed point and --check passes right after --write.
  const pass1 = await buildDirIndexes(allFiles, new Map([[ADR_README, adrOut]]));
  const ov = new Map([[ADR_README, adrOut], ...pass1.map((di) => [di.readmePath, di.desired])]);
  const dirIndexes = (await buildDirIndexes(allFiles, ov)).map((di) => ({ ...di, existing: di.readmePath === ADR_README ? adrOut : di.existing }));

  warnings.push(...(dirIndexes.arc42Warnings ?? []));
  const reportWarnings = () => {
    if (warnings.length === 0) return;
    console.warn(`\n[docs-graph] ${warnings.length} warning(s) (非block):`);
    for (const w of warnings) console.warn(`  ⚠️  ${w}`);
  };
  const failOnErrors = () => {
    if (errors.length === 0) return false;
    console.error(`\n[docs-graph] ${errors.length} ERROR(s) (CI block):`);
    for (const e of errors) console.error(`  ❌ ${e}`);
    return true;
  };

  if (arg === "--check") {
    let drift = false;
    const existingDeps = await readFile(OUTPUT, "utf8").catch(() => "");
    if (existingDeps.trim() !== depsOut.trim()) {
      console.error(`[docs-graph] ${OUTPUT_REL} is out of date. Run: --write`);
      drift = true;
    }
    if (adrExisting.trim() !== adrOut.trim()) {
      console.error(`[docs-graph] ${ADR_README_REL} ADR 索引が out of date. Run: --write`);
      drift = true;
    }
    for (const di of dirIndexes) {
      if (di.readmePath === ADR_README) { if (adrOut.trim() !== di.desired.trim() && adrExisting.trim() !== di.desired.trim()) { console.error(`[docs-graph] ${di.rel} の索引が out of date. Run: --write`); drift = true; } continue; }
      if (di.existing == null) { console.error(`[docs-graph] ${di.rel} が無い (ディレクトリ README + 索引は必須). Run: --write`); drift = true; }
      else if (di.existing.trim() !== di.desired.trim()) { console.error(`[docs-graph] ${di.rel} の索引が out of date. Run: --write`); drift = true; }
    }
    reportWarnings();
    const hasErrors = failOnErrors();
    if (drift || hasErrors) process.exit(1);
    console.log(`[docs-graph] OK — ${docs.length} docs, 索引/グラフ最新, schema/参照整合性 pass.`);
    return;
  }

  if (arg === "--write" || !arg) {
    reportWarnings();
    if (failOnErrors()) process.exit(1);
    await writeFile(OUTPUT, depsOut + "\n", "utf8");
    await writeFile(ADR_README, adrOut, "utf8");
    let dirWrites = 0;
    for (const di of dirIndexes) {
      if (di.existing == null || di.existing !== di.desired) { await writeFile(di.readmePath, di.desired, 'utf8'); dirWrites++; }
    }
    if (dirWrites) console.log(`[docs-graph] wrote ${dirWrites} directory README index(es).`);
    console.log(
      `[docs-graph] wrote ${OUTPUT_REL} + ${ADR_README_REL} ADR 索引 (${docs.length} docs).`,
    );
    return;
  }

  console.error(`Unknown arg: ${arg}. Use --check or --write.`);
  process.exit(2);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
