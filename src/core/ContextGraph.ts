/** まとまりの名前として使えるか。置き場所の表の `<c>` に当たる名前 (shared は全体共通のまとまり。tasks など固定のフォルダの名前は除く) */
function isContextName(name: string): boolean {
  if (name === SHARED_CONTEXT) return true;
  if (name.startsWith('.')) return false;
  // 約束 (context-contract) の `<c>` は、固定のフォルダ (shared・tasks) を除く。まとまりの名前の正本は置き場所の表
  return matchPlacement('context-contract', `ai/specs/${name}/contract.md`).ok;
}

/** まとまりのフォルダを持つ場所。まとまりの名前のフォルダが、この直下に並ぶ */
const CONTEXT_FOLDER_PARENTS: readonly string[] = ['person/design', 'ai/specs'];

/** まとまり `name` のフォルダ (person/design/<name>・ai/specs/<name>) が、どちらかにあるか (B6) */
export function hasContextFolder(docsDir: string, name: string): boolean {
  return isContextName(name) && CONTEXT_FOLDER_PARENTS.some((parent) => isDir(join(docsDir, parent, name)));
}

/** まとまりのフォルダの名前 (shared を除く) を、文字コード順に返す */
export function listContextFolders(docsDir: string): readonly string[] {
  const names = new Set<string>();
  for (const parent of CONTEXT_FOLDER_PARENTS) {
    const dir = join(docsDir, parent);
    if (!isDir(dir)) continue;
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory() && entry.name !== SHARED_CONTEXT && isContextName(entry.name)) names.add(entry.name);
    }
  }
  return [...names].sort();
}

/**
 * context-files・context-size が読む範囲 (B6): person/requirements/・person/design/shared/・person/design/<c>/・
 * ai/specs/shared/・ai/specs/<c>/ の文書 (README.md を除く)。加えて、自分のまとまり (context が <c>) の文書が参照する
 * 隣の約束 (context-contract)。--with-shared の有無で変わらない。決定の記録・手引き・提出物は含まない。
 */
export function readingSet(graph: ContextGraph, targetRoot: string, context: string): readonly ContextDoc[] {
  const folders = ['person/requirements/', 'person/design/shared/', `person/design/${context}/`, 'ai/specs/shared/', `ai/specs/${context}/`];
  const inRange = graph.docs.filter((doc) => folders.some((folder) => doc.docsRel.startsWith(folder)));
  const range = new Map<string, ContextDoc>(inRange.map((doc) => [doc.relPath, doc]));
  for (const doc of inRange) {
    if (doc.context !== context) continue;
    for (const ref of extractReferences(doc, graph, targetRoot)) {
      if (ref.target.kind === 'context-contract' && ref.target.context !== context) range.set(ref.target.relPath, ref.target);
    }
  }
  return [...range.values()];
}
