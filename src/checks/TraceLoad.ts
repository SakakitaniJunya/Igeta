// TraceCheck が読む入力: docs/ の設計書と、trace.code の glob に当たるコードのファイル。

import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { contextOfV4 } from '../core/ContextGraph.js';
import { readContext } from '../core/Context.js';
import { isDirectory, listDocFiles } from '../core/DocFiles.js';
import { parseFrontmatter, scalar } from '../core/Frontmatter.js';
import { detectLayout } from '../core/Role.js';
import type { CodeFile } from '../core/trace/CodeTags.js';
import type { TraceDocInput } from '../core/trace/TraceIndex.js';
import { matchesGlob } from '../gate/PathGlob.js';

const SKIP_DIRS = new Set(['node_modules', 'dist', 'coverage']);

/** docs/ の中の 1 文書 (docsRel は docs/ からの相対パス) を、索引の入力にする。生成索引 (AUTOGENERATED) は設計書ではないので undefined */
export function toDocInput(docsRel: string, text: string, isV4: boolean): TraceDocInput | undefined {
  const lines = text.split(/\r?\n/);
  if (lines[0]?.includes('AUTOGENERATED')) return undefined;
  const data = parseFrontmatter(lines)?.data ?? new Map();
  const kind = scalar(data, 'kind') ?? null;
  const context = isV4 ? contextOfV4(kind, docsRel, data) : readContext(kind, data);
  return { path: `docs/${docsRel}`, id: scalar(data, 'id') ?? null, context, lines };
}

/** 作業ツリーの docs/ の設計書。docs/ が無ければ空 (定義が 0 件の repo は検査しない) */
export function loadDocs(root: string): { readonly inputs: readonly TraceDocInput[]; readonly isV4: boolean } {
  const docsDir = join(root, 'docs');
  if (!isDirectory(docsDir)) return { inputs: [], isV4: false };
  const isV4 = detectLayout(docsDir) === 'v4';
  const inputs = listDocFiles(docsDir).flatMap((docsRel) => toDocInput(docsRel, readFileSync(join(docsDir, docsRel), 'utf8'), isV4) ?? []);
  return { inputs, isV4 };
}

/** trace.code の glob に当たるファイル (repo 直下からの相対パス)。node_modules・dist・点で始まるフォルダは辿らない */
export function loadCodeFiles(root: string, globs: readonly string[]): CodeFile[] {
  if (globs.length === 0) return [];
  const found: CodeFile[] = [];
  const walk = (dir: string, prefix: string): void => {
    for (const entry of readdirSync(join(root, dir), { withFileTypes: true }).sort((left, right) => left.name.localeCompare(right.name))) {
      const path = prefix === '' ? entry.name : `${prefix}/${entry.name}`;
      if (entry.isDirectory() && !SKIP_DIRS.has(entry.name) && !entry.name.startsWith('.')) walk(path, path);
      else if (entry.isFile() && globs.some((glob) => matchesGlob(path, glob))) {
        found.push({ path, lines: readFileSync(join(root, path), 'utf8').split(/\r?\n/) });
      }
    }
  };
  walk('', '');
  return found;
}
