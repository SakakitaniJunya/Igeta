/** 生成索引 (docs/ 直下の 2 本と各フォルダの README.md)。置き場所の表の外に置いてよい */
const INDEXES: readonly string[] = [
  'README.md',
  'dependencies.md',
  'person/README.md',
  'person/design/reservation/flows/README.md',
  'ai/specs/README.md',
  'client/delivery/spec-v1/README.md',
];

function writeValidTree(root: string): void {
  for (const [path, kind, context] of VALID) write(root, `docs/${path}`, doc(kind, context ?? null));
  for (const path of INDEXES) write(root, `docs/${path}`, '<!-- AUTOGENERATED BY scripts/generate-docs-graph.mjs -->\n# 索引\n');
}

interface RunResult {
  readonly violations: readonly Violation[];
  readonly warnings: readonly string[];
  /** 違反の file (リポジトリルートからの相対パス) を / 区切りにして並べたもの */
  readonly files: readonly string[];
}

function run(root: string, igetaRoot: string = IGETA_ROOT): RunResult {
  const check = new RoleBoundaryCheck();
  const violations = check.run({ targetRoot: root, igetaRoot });
  return {
    violations,
    warnings: check.warnings,
    files: violations.map((violation) => (violation.file ?? '').split('\\').join('/')),
  };
}

/** 版だけを持つ Igeta の package.json の置き場所 */
function igetaRootWithVersion(version: string): string {
  const igetaRoot = makeRoot();
  write(igetaRoot, 'package.json', JSON.stringify({ name: 'igeta', version }));
  return igetaRoot;
}

const messageOf = (result: RunResult, file: string): string =>
  result.violations.find((violation) => (violation.file ?? '').split('\\').join('/') === file)?.message ?? '';

