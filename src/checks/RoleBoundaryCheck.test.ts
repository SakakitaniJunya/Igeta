const workspaces: string[] = [];

after(() => {
  for (const dir of workspaces) rmSync(dir, { recursive: true, force: true });
});

function makeRoot(): string {
  const root = mkdtempSync(join(tmpdir(), 'igeta-roleboundary-'));
  workspaces.push(root);
  return root;
}

function write(root: string, relPath: string, content: string): void {
  const target = join(root, relPath);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content);
}

/** frontmatter に kind (と context) だけを書いた文書。body は本文の行 */
function doc(kind: string | null, context: string | null = null, body: readonly string[] = []): string {
  return [
    ...(kind === null && context === null
      ? []
      : ['---', ...(kind === null ? [] : [`kind: ${kind}`]), ...(context === null ? [] : [`context: ${context}`]), '---', '']),
    '# 題名',
    '',
    ...body,
    '',
  ].join('\n');
}

