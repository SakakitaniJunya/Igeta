// context-files・context-size を回し、新しい構成の検査を足す前 (a9fdd0c) の build が同じ木から作った出力と比べる。
// 旧い構成の警告の文 (LEGACY_LAYOUT_MESSAGE) だけは、この版で意図して変えたので、定数で比べる。
