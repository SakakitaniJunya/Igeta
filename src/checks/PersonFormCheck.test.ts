/** テスト用の git 操作。利用者の git の設定 (署名・既定のブランチ名) に左右されないようにする */
function git(root: string, ...args: string[]): string {
  return execFileSync(
    'git',
    ['-C', root, '-c', 'user.name=igeta-test', '-c', 'user.email=igeta-test@example.com', '-c', 'commit.gpgsign=false', ...args],
    { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] },
  ).trim();
}

function commit(root: string, message: string): void {
  git(root, 'add', '-A');
  git(root, 'commit', '-q', '-m', message);
}

/** 正しい構成を 1 コミットにした git repo。ブランチ名は dest (変更を入れる先) */
function makeRepo(): string {
  const root = makeRoot();
  git(root, 'init', '-q');
  writeValidTree(root);
  commit(root, '宛先: 廃の行を持つ正しい構成');
  git(root, 'branch', '-M', 'dest');
  return root;
}

