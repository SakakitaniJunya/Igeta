/** frontmatter (kind が無い文書も作れる) と題名の次から、本文の行 */
function titled(id: string, kind: string | null, body: readonly string[], extra: readonly string[] = []): string[] {
  return [
    '---',
    `id: ${id}`,
    `title: ${id} の題名`,
    'type: design',
    ...(kind === null ? [] : [`kind: ${kind}`]),
    ...extra,
    'status: active',
    'owners: [product]',
    '---',
    '',
    `# ${id}`,
    '',
    ...body,
  ];
}

const marker = (name: string, edge: 'start' | 'end'): string =>
  edge === 'start'
