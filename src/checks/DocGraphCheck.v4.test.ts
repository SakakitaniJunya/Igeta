const workspaces: string[] = [];

after(() => {
  for (const dir of workspaces) rmSync(dir, { recursive: true, force: true });
});

function makeRoot(): string {
  const root = mkdtempSync(join(tmpdir(), 'igeta-graph-v4-'));
  workspaces.push(root);
  return root;
}

function write(root: string, relPath: string, lines: readonly string[]): void {
  const target = join(root, relPath);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, `${lines.join('\n')}\n`);
}

interface DocOptions {
  readonly type?: string;
  readonly arc42?: number;
  readonly status?: string;
  readonly dependsOn?: readonly string[];
  readonly relatesTo?: readonly string[];
  readonly context?: string;
  readonly body?: readonly string[];
}

/** 索引と参照の検査が読む frontmatter と、本文の行 */
function doc(id: string, kind: string, options: DocOptions = {}): string[] {
  const { type = 'design', arc42, status = 'active', dependsOn = [], relatesTo = [], context, body = [] } = options;
  return [
    '---',
    `id: ${id}`,
    `title: ${id} の題名`,
    `type: ${type}`,
    `kind: ${kind}`,
    ...(arc42 === undefined ? [] : [`arc42: ${arc42}`]),
    ...(context === undefined ? [] : [`context: ${context}`]),
    `status: ${status}`,
    'owners: [eng]',
    `depends_on: [${dependsOn.join(', ')}]`,
    `relates_to: [${relatesTo.join(', ')}]`,
    '---',
    '',
    `# ${id}`,
    '',
    ...body,
  ];
}

function adr(number: string, slug: string, status: string, extra: readonly string[] = []): string[] {
  return doc(`adr-${number}-${slug}`, 'adr', { type: 'adr', arc42: 9, status, body: extra });
}

