interface RunResult {
  readonly violations: readonly Violation[];
  readonly warnings: readonly string[];
  readonly detail: string;
}

async function run(root: string, mode: 'write' | 'check'): Promise<RunResult> {
  const check = new DocGraphCheck(mode === 'write' ? { write: true } : {});
  const violations = await check.run({ targetRoot: root, igetaRoot: IGETA_ROOT });
  return {
    violations,
    warnings: check.warnings,
    detail: [...violations.map((violation) => `${violation.file ?? ''} ${violation.message}`), ...check.warnings].join('\n'),
  };
}

/** 新規の木は、1 回目の write が README を作り、それが 2 回目のグラフの節点になるので、2 回で収束する */
async function converge(root: string): Promise<void> {
  assert.deepEqual((await run(root, 'write')).violations, []);
  assert.deepEqual((await run(root, 'write')).violations, []);
}

const read = (root: string, relPath: string): string => readFileSync(join(root, relPath), 'utf8');

/** 文書の中で、prefix で始まる最初の行の行番号 (1 始まり)。無ければ 0 */
const lineOf = (root: string, relPath: string, prefix: string): number =>
  read(root, relPath).split('\n').findIndex((line) => line.startsWith(prefix)) + 1;

