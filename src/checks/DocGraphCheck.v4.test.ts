describe('DocGraphCheck: 旧い構成の ADR 索引は変えない', () => {
  function writeLegacyTree(root: string): void {
    write(root, 'docs/product/requirements.md', doc('requirements', 'requirements', { arc42: 1 }));
    write(root, 'docs/adr/0001-x.md', adr('0001', 'x', 'accepted'));
    write(root, 'docs/adr/README.md', [
      '---', 'id: adr-index', 'title: ADR — 索引', 'type: index', 'status: active', 'owners: [eng]', '---', '',
      '# adr', '', '## 索引', '',
      '<!-- AUTOGEN:adr-index:start — generated by scripts/generate-docs-graph.mjs, do not edit by hand -->',
      '<!-- AUTOGEN:adr-index:end -->',
    ]);
  }

  it('docs/adr/README.md に、ファイル名のリンクで索引を出し、docs/person/ は作らない', async () => {
    const root = makeRoot();
    writeLegacyTree(root);
    await converge(root);
    assert.match(read(root, 'docs/adr/README.md'), /\| \[0001\]\(0001-x\.md\) \| adr-0001-x の題名 \| accepted \|/);
    assert.equal(existsSync(join(root, 'docs', 'person')), false);
    assert.deepEqual((await run(root, 'check')).violations, []);
  });

  it('ADR があるのに docs/adr/README.md が無ければ、これまでの文言で落ちる', async () => {
    const root = makeRoot();
    writeLegacyTree(root);
    rmSync(join(root, 'docs', 'adr', 'README.md'));
    const result = await run(root, 'check');
    assert.equal(result.violations.length, 1, result.detail);
    assert.equal(result.violations[0]?.message, '[docs-graph] docs/adr/README.md が無い (ADR があるツリーでは ADR 索引が必須). Run: --write');
  });

  it('amended は旧い構成の語彙に無く、これまでどおり許可外', async () => {
    const root = makeRoot();
    writeLegacyTree(root);
    write(root, 'docs/adr/0002-y.md', adr('0002', 'y', 'amended'));
    const result = await run(root, 'write');
    assert.equal(result.violations.length, 1, result.detail);
    assert.match(result.violations[0]?.message ?? '', /status="amended" は許可外 \(adr: proposed\|accepted\|deprecated\|superseded\|rejected\|template\)/);
  });

  it('旧い構成の docs/adr/ の番号の重複は、これまでどおり落ちる', async () => {
    const root = makeRoot();
    writeLegacyTree(root);
    write(root, 'docs/adr/0001-other.md', adr('0009', 'other', 'accepted'));
    const result = await run(root, 'check');
    assert.equal(result.violations.length, 1, result.detail);
    assert.match(result.violations[0]?.message ?? '', /ADR 番号の重複検出[\s\S]*ADR-0001/);
  });
});

